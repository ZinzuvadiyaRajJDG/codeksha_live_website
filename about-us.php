        // FAQ accordion
        const faqItems = document.querySelectorAll('.faq-item');
        const setFaqHeight = (item) => {
          const answer = item.querySelector('.faq-answer');
          if (!answer) return;
          answer.style.maxHeight = item.classList.contains('active') ? answer.scrollHeight + 30 + 'px' : '0px';
        };
        faqItems.forEach(item => {
          const question = item.querySelector('.faq-question');
          if (!question) return;
          question.addEventListener('click', () => {
            const isActive = item.classList.contains('active');
            faqItems.forEach(otherItem => {
              otherItem.classList.remove('active');
              const icon = otherItem.querySelector('.icon');
              if (icon) icon.className = 'fa-solid fa-plus icon';
              setFaqHeight(otherItem);
            });
            if (!isActive) {
              item.classList.add('active');
              const icon = item.querySelector('.icon');
              if (icon) icon.className = 'fa-solid fa-minus icon';
              setFaqHeight(item);
            }
          });
        });
        setFaqHeight(document.querySelector('.faq-item.active') || faqItems[0]);

        // Animated stat counters
        const statWrap = document.getElementById('aboutStats');
        if (statWrap) {
          const run = () => {
            statWrap.querySelectorAll('.num').forEach(el => {
              const target = parseFloat(el.dataset.count);
              const decimals = parseInt(el.dataset.decimals || '0', 10);
              const suffix = el.dataset.suffix || '';
              const dur = 1400;
              const start = performance.now();
              const tick = (now) => {
                const p = Math.min((now - start) / dur, 1);
                const eased = 1 - Math.pow(1 - p, 3);
                let val = target * eased;
                el.textContent = (decimals ? val.toFixed(decimals) : Math.round(val).toLocaleString('en-IN')) + (p === 1 ? suffix : '');
                if (p < 1) requestAnimationFrame(tick);
                else el.textContent = (decimals ? target.toFixed(decimals) : Math.round(target).toLocaleString('en-IN')) + suffix;
              };
              requestAnimationFrame(tick);
            });
          };
          if ('IntersectionObserver' in window) {
            const io = new IntersectionObserver((entries) => {
              entries.forEach(e => { if (e.isIntersecting) { run(); io.disconnect(); } });
            }, { threshold: 0.3 });
            io.observe(statWrap);
          } else {
            run();
          }
        }
      });
