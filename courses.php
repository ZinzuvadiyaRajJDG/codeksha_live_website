    <script>
      document.addEventListener('DOMContentLoaded', () => {
        if (window.lucide) lucide.createIcons();

        const hamburgerBtn = document.getElementById('hamburgerBtn');
        const navLinks = document.getElementById('navLinks');
        const navOverlay = document.getElementById('navOverlay');
        if (hamburgerBtn && navLinks) {
          const toggleMenu = () => {
            const isActive = navLinks.classList.toggle('active');
            if (navOverlay) navOverlay.classList.toggle('active', isActive);
            const icon = hamburgerBtn.querySelector('i');
            if (icon) icon.className = isActive ? 'fa-solid fa-xmark' : 'fa-solid fa-bars';
          };
          hamburgerBtn.addEventListener('click', toggleMenu);
          if (navOverlay) navOverlay.addEventListener('click', toggleMenu);
          navLinks.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
            if (navLinks.classList.contains('active')) toggleMenu();
          }));
        }

        // Course category filter
        const pills = document.querySelectorAll('#courseFilterBar .category-filter-pill');
        const tiles = document.querySelectorAll('#coursesGrid .course-tile');
        const applyFilter = (filter) => {
          pills.forEach(p => p.classList.toggle('active', p.getAttribute('data-filter') === filter));
          tiles.forEach(tile => {
            tile.style.display = (filter === 'all' || tile.getAttribute('data-category') === filter) ? '' : 'none';
          });
        };
        pills.forEach(pill => {
          pill.addEventListener('click', () => applyFilter(pill.getAttribute('data-filter')));
        });

        // Arrive pre-filtered from the homepage category pills (#web-development etc., or legacy ?filter=...)
        const slugOf = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
        const hashSlug = window.location.hash.replace(/^#/, '');
        const requestedFilter = new URLSearchParams(location.search).get('filter');
        const matchPill = [...pills].find(p => hashSlug && slugOf(p.getAttribute('data-filter')) === hashSlug)
          || [...pills].find(p => requestedFilter && p.getAttribute('data-filter') === requestedFilter);
        if (matchPill) applyFilter(matchPill.getAttribute('data-filter'));
      });
    </script>
