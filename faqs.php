    <script>
      document.addEventListener('DOMContentLoaded', () => {
        if (window.lucide) lucide.createIcons();

        const hamburgerBtn = document.getElementById('hamburgerBtn');
        const navLinks = document.getElementById('navLinks');
        const navOverlay = document.getElementById('navOverlay');
        if (hamburgerBtn && navLinks) {
          const toggleMenu = () => {
            const isActive = navLinks.classList.toggle('active');
            if (navOverlay) navOverlay.classList.toggle('active', isActive);
            const icon = hamburgerBtn.querySelector('i');
            if (icon) icon.className = isActive ? 'fa-solid fa-xmark' : 'fa-solid fa-bars';
          };
          hamburgerBtn.addEventListener('click', toggleMenu);
          if (navOverlay) navOverlay.addEventListener('click', toggleMenu);
          navLinks.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
            if (navLinks.classList.contains('active')) toggleMenu();
          }));
        }

        // FAQ accordions (scoped per category group so each group has its own single-open behavior)
        document.querySelectorAll('.faq-category-group').forEach(group => {
          const faqItems = group.querySelectorAll('.faq-item');
          const setFaqHeight = (item) => {
            const answer = item.querySelector('.faq-answer');
            if (!answer) return;
            answer.style.maxHeight = item.classList.contains('active') ? answer.scrollHeight + 30 + 'px' : '0px';
          };
          faqItems.forEach(item => {
            const question = item.querySelector('.faq-question');
            if (!question) return;
            question.addEventListener('click', () => {
              const isActive = item.classList.contains('active');
              faqItems.forEach(otherItem => {
                otherItem.classList.remove('active');
                const icon = otherItem.querySelector('.icon');
                if (icon) icon.className = 'fa-solid fa-plus icon';
                setFaqHeight(otherItem);
              });
              if (!isActive) {
                item.classList.add('active');
                const icon = item.querySelector('.icon');
                if (icon) icon.className = 'fa-solid fa-minus icon';
                setFaqHeight(item);
              }
            });
          });
          setFaqHeight(group.querySelector('.faq-item.active') || faqItems[0]);
        });

        // Category tab scroll navigation
        const tabs = document.querySelectorAll('#faqCategoryTabs .faq-category-tab');
        tabs.forEach(tab => {
          tab.addEventListener('click', () => {
            tabs.forEach(t => t.classList.remove('active'));
            tab.classList.add('active');
            const target = document.getElementById(tab.getAttribute('data-target'));
            if (target) target.scrollIntoView({ behavior: 'smooth', block: 'start' });
          });
        });
      });
    </script>
