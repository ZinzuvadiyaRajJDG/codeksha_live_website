<h2 id="mistakes">Common Mistakes That Slow Beginners Down</h2>
<ol class="post-steps">
  <li><strong>Tutorial hell.</strong> Watching videos without building. After every tutorial, build something similar without the video.</li>
  <li><strong>Jumping to React too early.</strong> If JavaScript feels shaky, React will feel impossible. Finish Phase 3 properly.</li>
  <li><strong>Learning three stacks at once.</strong> Depth in one stack beats a shallow tour of several.</li>
  <li><strong>Copying AI output you do not understand.</strong> Use AI to learn faster, but be able to explain every line in an interview.</li>
  <li><strong>Never deploying.</strong> A live link is far more convincing than a screenshot.</li>
  <li><strong>Skipping Git.</strong> Every team uses it; start from week one.</li>
</ol>

