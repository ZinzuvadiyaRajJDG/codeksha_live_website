<h2 id="projects">Projects to Build (and What Each One Proves)</h2>
<ol class="post-steps">
  <li><strong>Personal portfolio website.</strong> Proves HTML, CSS, responsive design and deployment. Link every other project from here.</li>
  <li><strong>To-do or notes app with local storage.</strong> Proves JavaScript, the DOM and event handling.</li>
  <li><strong>API-powered app (weather, movies or news).</strong> Proves <code>fetch</code>, async code, React state and loading/error handling.</li>
  <li><strong>Full stack CRUD app (blog, job board or expense tracker).</strong> Proves React, a Node/Express API, a database and authentication end to end.</li>
  <li><strong>E-commerce or booking mini project.</strong> Proves relationships, carts, roles, payments (test mode) and a deployed live URL.</li>
</ol>
