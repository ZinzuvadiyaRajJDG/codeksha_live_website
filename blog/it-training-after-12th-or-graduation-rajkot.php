          const spy = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
              const link = document.querySelector('.toc-list a[href="#' + entry.target.id + '"]');
              if (!link) return;
              if (entry.isIntersecting) {
                tocLinks.forEach(l => l.classList.remove('active'));
